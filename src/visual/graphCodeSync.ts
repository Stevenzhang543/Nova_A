/** 将旧图变量名转换为可生成的 ASCII 标识符，空结果使用 value。 */
function safeIdentifier(value: string): string { return value.replace(/[^A-Za-z0-9_]/g, '_').replace(/^[^A-Za-z_]+/, '') || 'value' }
/** 忽略空行和自动追踪语句，保留用于比较的实际程序行。 */
