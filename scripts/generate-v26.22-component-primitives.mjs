/** 版本26.22：从组件声明提取可编辑基础类型与字段描述，生成运行时约束与 schema 驱动所需的元数据。
 * 单一来源：本脚本是 componentPrimitiveTypes.ts 与 componentFieldDescriptions.ts 的唯一生成者，
 * 两者必须同时更新，避免出现第二张并行表（主指令 §6/§31）。 */
import ts from 'typescript'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'
import { runtimeComponentFields22 } from './fixtures/v26.22-property-dispositions.mjs'

const SOURCE_PATH = 'src/world/components.ts'
const PRIMITIVES_PATH = 'src/world/componentPrimitiveTypes.ts'
const DESCRIPTIONS_PATH = 'src/world/componentFieldDescriptions.ts'
const CONSTRUCTORS_PATH = '.cache/v2622-component-primitive-constructors.json'
const SKIPPED_FIELDS = ['kind', 'uuid', 'removed']

const program = ts.createProgram([SOURCE_PATH], {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  strictNullChecks: true,
  skipLibCheck: true,
})
const checker = program.getTypeChecker()
const source = program.getSourceFile(SOURCE_PATH)
assert.ok(source, 'component source must be readable')

/** 从联合类型中收集字符串字面量；非联合类型只在自身是字符串字面量时返回单值。 */
const literals = (type) => type.isUnion() ? type.types.flatMap(literals) : (type.flags & ts.TypeFlags.StringLiteral ? [type.value] : [])

/** 递归解析联合类型的基础类型集合；出现不支持的成员时返回 null 表示不可静态判定。 */
function primitive(type) {
  if (type.isUnion()) {
    const parts = type.types.map(primitive)
    return parts.every(Boolean) ? [...new Set(parts.flat())].sort() : null
  }
  if (type.flags & ts.TypeFlags.NumberLike) return ['number']
  if (type.flags & ts.TypeFlags.StringLike) return ['string']
  if (type.flags & ts.TypeFlags.BooleanLike) return ['boolean']
  if (type.flags & ts.TypeFlags.Null) return ['null']
  if (type.flags & ts.TypeFlags.Undefined) return ['undefined']
  return null
}

/** 仅提取源码里可直接读出的字面量默认值；无法静态判定的初始化表达式返回 undefined，不做推测。 */
function literalDefault(initializer) {
  if (!initializer) return undefined
  if (ts.isNumericLiteral(initializer)) return Number(initializer.text)
  if (ts.isStringLiteral(initializer)) return initializer.text
  if (initializer.kind === ts.SyntaxKind.TrueKeyword) return true
  if (initializer.kind === ts.SyntaxKind.FalseKeyword) return false
  if (initializer.kind === ts.SyntaxKind.NullKeyword) return null
  if (ts.isPrefixUnaryExpression(initializer) && ts.isNumericLiteral(initializer.operand)) {
    const value = Number(initializer.operand.text)
    if (initializer.operator === ts.SyntaxKind.MinusToken) return -value
    if (initializer.operator === ts.SyntaxKind.PlusToken) return value
  }
  return undefined
}

const contracts = {}
const descriptions = {}
const constructors = {}

for (const declaration of source.statements.filter(ts.isClassDeclaration)) {
  const name = declaration.name?.text
  if (!name || name === 'ComponentBase') continue
  const fields = { enabled: ['boolean'] }
  const described = { enabled: { types: ['boolean'], optional: false, default: undefined } }
  for (const member of declaration.members.filter(ts.isPropertyDeclaration)) {
    const field = member.name.getText(source)
    const hidden = member.modifiers?.some(/** 私有与受保护字段不属于持久化契约。 */ x => [ts.SyntaxKind.PrivateKeyword, ts.SyntaxKind.ProtectedKeyword].includes(x.kind))
    if (SKIPPED_FIELDS.includes(field) || runtimeComponentFields22[name]?.[field] || hidden) continue
    const types = primitive(checker.getTypeAtLocation(member))
    if (!types) continue
    fields[field] = types
    described[field] = { types, optional: member.questionToken !== undefined, default: literalDefault(member.initializer) }
  }
  const identity = declaration.members.find(/** 找到声明组件种类的 kind 字段。 */ x => ts.isPropertyDeclaration(x) && x.name.getText(source) === 'kind')
  const kinds = identity ? literals(checker.getTypeAtLocation(identity)) : []
  for (const kind of kinds.length ? kinds : [name]) {
    contracts[kind] = fields
    descriptions[kind] = described
    constructors[kind] = name
  }
}

/** 去掉不可序列化的 undefined 默认值，使生成物只包含真实存在的事实。 */
function serializable(table) {
  const out = {}
  for (const [kind, fields] of Object.entries(table)) {
    const next = {}
    for (const [field, value] of Object.entries(fields)) {
      next[field] = value.default === undefined
        ? { types: value.types, optional: value.optional }
        : { types: value.types, optional: value.optional, default: value.default }
    }
    out[kind] = next
  }
  return out
}

const primitivesText = '/** 组件原始类型契约：列出各持久化字段允许的基本类型，供写入前校验使用。 */\n'
  + '// Generated by scripts/generate-v26.22-component-primitives.mjs; verify with --check.\n'
  + '// Declared authored primitive fields only; structured values retain their specific owners.\n'
  + 'export const componentPrimitiveTypes: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = '
  + JSON.stringify(contracts, null, 2) + '\n'

const descriptionsText = '/** 组件字段描述：由组件声明派生，供 schema 驱动 Inspector 与校验使用。 */\n'
  + '// Generated by scripts/generate-v26.22-component-primitives.mjs; verify with --check.\n'
  + '// 只包含源码可证明的事实（允许类型、静态默认值、是否可选）；范围/单位/控件/i18n 属于策展内容，不在此处编造。\n'
  + 'export interface ComponentFieldDescription {\n'
  + '  readonly types: readonly string[]\n'
  + '  readonly optional: boolean\n'
  + '  readonly default?: string | number | boolean | null\n'
  + '}\n\n'
  + 'export const componentFieldDescriptions: Readonly<Record<string, Readonly<Record<string, ComponentFieldDescription>>>> = '
  + JSON.stringify(serializable(descriptions), null, 2) + '\n'

const check = process.argv.includes('--check')
const same = (actual, expected) => (actual ?? '').replace(/\r\n/g, '\n') === expected
const readOrEmpty = async (path) => { try { return await readFile(path, 'utf8') } catch { return '' } }

if (check) {
  assert.ok(same(await readOrEmpty(PRIMITIVES_PATH), primitivesText), PRIMITIVES_PATH + ' is stale; re-run without --check')
  assert.ok(same(await readOrEmpty(DESCRIPTIONS_PATH), descriptionsText), DESCRIPTIONS_PATH + ' is stale; re-run without --check')
} else {
  await writeFile(PRIMITIVES_PATH, primitivesText)
  await writeFile(DESCRIPTIONS_PATH, descriptionsText)
}
await mkdir('.cache', { recursive: true })
await writeFile(CONSTRUCTORS_PATH, JSON.stringify(constructors))
console.log(JSON.stringify({
  components: Object.keys(contracts).length,
  fields: Object.values(contracts).reduce(/** 累加每个组件的字段数。 */ (n, x) => n + Object.keys(x).length, 0),
  withStaticDefault: Object.values(descriptions).reduce(/** 统计可从源码读出的默认值数量。 */ (n, x) => n + Object.values(x).filter(/** 只计入确实带默认值的字段。 */ f => f.default !== undefined).length, 0),
}))
