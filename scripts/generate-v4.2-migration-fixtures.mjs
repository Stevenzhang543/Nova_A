import { spawnSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const fixture = JSON.parse(await readFile(join(root, 'tests/fixtures/migrations/public-schema-inputs.json'), 'utf8'))
const outputRoot = join(root, 'reference-projects', 'migrations')
await mkdir(outputRoot, { recursive: true })
const results = []
async function resilientWrite(path, contents) {
  let lastError
  for (let attempt = 0; attempt < 8; attempt++) {
    try { await writeFile(path, contents, 'utf8'); return }
    catch (error) { lastError = error; await new Promise(resolve => setTimeout(resolve, 75 * (attempt + 1))) }
  }
  throw lastError
}

for (const schema of fixture.publicSchemas) {
  const folder = join(outputRoot, `schema-${String(schema).padStart(2, '0')}`)
  await mkdir(folder, { recursive: true })
  const before = { ...structuredClone(fixture.baseProject), formatVersion: schema }
  const source = `${JSON.stringify(before, null, 2)}\n`
  const run = spawnSync('cargo', ['run', '--quiet', '-p', 'nova_format', '--example', 'migrate_fixture', '--locked'], { cwd: root, input: source, encoding: 'utf8' })
  if (run.status !== 0) throw new Error(`Schema ${schema} migration fixture failed: ${run.stderr || run.stdout}`)
  const expected = run.stdout.replace(/\r\n?/g, '\n')
  await resilientWrite(join(folder, 'pre-migration.nova'), source)
  await resilientWrite(join(folder, 'expected-migrated.nova'), expected.endsWith('\n') ? expected : `${expected}\n`)
  await resilientWrite(join(folder, 'README.md'), `# Schema ${schema} migration fixture\n\n- Input: \`pre-migration.nova\`\n- Expected deterministic output: \`expected-migrated.nova\`\n- Command: \`cargo run -p nova_format --example migrate_fixture --locked < pre-migration.nova\`\n- Acceptance: schema 29, engine 5.0.0, frozen 5.x compatibility boundary, preserved unknown marker, valid references, and byte-identical repeat migration.\n`)
  results.push({ schema, inputBytes: Buffer.byteLength(source), outputBytes: Buffer.byteLength(expected), status: 'passed' })
}

await resilientWrite(join(outputRoot, 'migration-results.json'), `${JSON.stringify({ format: 'nova-v5.0-migration-fixtures', version: 1, generatedAt: new Date().toISOString(), sourceSchemas: fixture.publicSchemas, targetSchema: 29, targetEngine: '5.0.0', maximumEngineExclusive: '6.0.0', results, status: 'passed' }, null, 2)}\n`)
await resilientWrite(join(outputRoot, 'README.md'), '# Nova_A v5.0 migration reference projects\n\nThis directory contains the complete supported schema 5–29 input/output matrix. Each expected file is generated by the same pinned Rust format authority used by desktop and WASM builds. Schema remains 29 while the 5.0 compatibility seal advances compatible projects to the frozen 5.x `<6.0.0` engine boundary. Malformed, missing, duplicate, and future-schema rejection cases remain in the Rust and fault/fuzz suites.\n')
console.log(`Generated ${results.length} pre-migration and expected-result pairs.`)
